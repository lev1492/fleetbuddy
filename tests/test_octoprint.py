def test_plugin_upload_with_order_options(env, monkeypatch):
    main = env["main"]
    from app import production
    main.svc.printers["SN1"] = {"sn": "SN1", "name": "S5", "model": "UltiMaker S5"}
    monkeypatch.setattr(production, "check", lambda _svc, _f, sn: (True, ""))
    pid = main.svc.db.x("INSERT INTO projects(name, created_at) VALUES('Clienti', 0)")
    h = {"X-Api-Key": env["key"], "User-Agent": "Cura/5.9.0 FabbrixFarmManager-Cura/1.0.0"}
    r = env["client"].post("/slicer/v1/upload", headers=h, files={"file": ("staffa.gcode", GCODE.encode())},
                           data={"project_id": str(pid), "target": "p:SN1", "action": "order", "copies": "3",
                                 "priority": "3", "notes": "Cliente Rossi"})
    assert r.status_code == 200, r.text
    out = r.json()
    f = main.svc.db.one("SELECT * FROM files WHERE id=?", (out["file_id"],))
    assert f["project_id"] == pid and f["notes"] == "Cliente Rossi" and f["source"] == "cura"
    prod = main.svc.db.one("SELECT * FROM productions WHERE id=?", (out["production_id"],))
    assert prod["priority"] == 3 and prod["printers"] == '["SN1"]'
    assert main.svc.db.one("SELECT COUNT(*) n FROM production_units WHERE production_id=?", (prod["id"],))["n"] == 3
    # operatore: priorità ignorata (solo amministratore e Manager la scelgono)
    main.svc.db.set_setting("ui_settings", {"slicer_admin_only": False})
    op = main.auth.create_user("mario", "Password123", "operator")
    main.svc.db.x("INSERT INTO access(user_id, kind, ref) VALUES(?, 'project', ?)", (op, str(pid)))
    main.svc.db.x("INSERT INTO access(user_id, kind, ref) VALUES(?, 'printer', 'SN1')", (op,))
    _, key = main.auth.create_api_key(op, "orca")
    r = env["client"].post("/slicer/v1/upload", headers={"X-Api-Key": key}, files={"file": ("b.gcode", (GCODE + "; b\n").encode())},
                           data={"project_id": str(pid), "target": "", "action": "order", "priority": "3"})
    assert r.status_code == 200, r.text
    assert main.svc.db.one("SELECT priority FROM productions WHERE id=?", (r.json()["production_id"],))["priority"] == 1
    # cartella non consentita
    r = env["client"].post("/slicer/v1/upload", headers={"X-Api-Key": key}, files={"file": ("c.gcode", b"G28\n")},
                           data={"project_id": "none"})
    assert r.status_code == 403


