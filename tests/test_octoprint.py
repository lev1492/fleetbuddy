def test_pairing_flow(env):
    c = env["client"]
    r = c.post("/slicer/v1/pair", json={"app": "Cura", "device": "PC-UFFICIO"})
    assert r.status_code == 200, r.text
    rid, code = r.json()["request_id"], r.json()["code"]
    assert r.json()["approve_url"].endswith(f"/#pair={code}")
    assert c.get(f"/slicer/v1/pair/{rid}").status_code == 202
    assert c.post(f"/api/slicer/pair/{code}", json={"approve": True}).status_code == 401      # serve la sessione
    assert c.post("/api/login", json={"username": "admin", "password": "Password123"}).status_code == 200
    assert c.get(f"/api/slicer/pair/{code.lower()}").json()["device"] == "PC-UFFICIO"
    assert c.post(f"/api/slicer/pair/{code}", json={"approve": True}).json()["name"] == "Cura – PC-UFFICIO"
    r = c.get(f"/slicer/v1/pair/{rid}")
    assert r.status_code == 200 and r.json()["key"].startswith("ffm_") and r.json()["user"] == "admin"
    assert c.get(f"/slicer/v1/pair/{rid}").status_code == 404                                 # consegnata una volta sola
    info = c.get("/slicer/v1/info", headers={"X-Api-Key": r.json()["key"]}).json()
    assert info["perms"] == {"upload": True, "order": True, "prioritize": True}
    assert info["projects"][0]["id"] is None


