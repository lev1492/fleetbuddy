def test_upload_archives_file(env):
    r = up(env)
    assert r.status_code == 201, r.text
    body = r.json()
    assert body["done"] and body["files"]["local"]["name"] == "pezzo.gcode"
    assert r.headers["location"].endswith("/octoprint/api/files/local/pezzo.gcode")
    f = env["main"].svc.db.one("SELECT * FROM files WHERE id=?", (body["fabbrix"]["file_id"],))
    assert f["source"] == "prusaslicer" and f["uploaded_by"] == env["admin"] and f["project_id"] is None
    # stesso contenuto: nessun doppione, risposta comunque positiva
    r2 = up(env, name="altro.gcode")
    assert r2.status_code == 201 and r2.json()["fabbrix"]["duplicate"] is True


def test_upload_folder_from_path(env):
    db = env["main"].svc.db
    assert up(env, path="Clienti/Rossi").status_code == 400            # cartella inesistente
    top = db.x("INSERT INTO projects(name, created_at) VALUES('Clienti', 0)")
    sub = db.x("INSERT INTO projects(name, parent_id, created_at) VALUES('Rossi', ?, 0)", (top,))
    r = up(env, path="clienti\\ROSSI")                                  # separatori Windows, maiuscole diverse
    assert r.status_code == 201, r.text
    assert db.one("SELECT project_id FROM files WHERE id=?", (r.json()["fabbrix"]["file_id"],))["project_id"] == sub


def test_default_folder_and_permissions(env):
    main = env["main"]
    db = main.svc.db
    pid = db.x("INSERT INTO projects(name, created_at) VALUES('Officina', 0)")
    op = main.auth.create_user("mario", "Password123", "operator")
    _, key = main.auth.create_api_key(op, "orca")
    r = up(env, key=key, path="Officina")                              # predefinito: solo amministratori
    assert r.status_code == 403 and "amministratori" in r.json()["error"]
    db.set_setting("ui_settings", {"slicer_admin_only": False})
    assert up(env, key=key).status_code == 400                         # né percorso né cartella predefinita
    assert up(env, key=key, path="Officina").status_code == 403         # cartella non consentita
    db.x("INSERT INTO access(user_id, kind, ref) VALUES(?, 'project', ?)", (op, str(pid)))
    db.x("UPDATE users SET default_project=? WHERE id=?", (pid, op))
    r = up(env, key=key)
    assert r.status_code == 201, r.text
    assert db.one("SELECT project_id FROM files WHERE id=?", (r.json()["fabbrix"]["file_id"],))["project_id"] == pid
    viewer = main.auth.create_user("ospite", "Password123", "viewer")
    _, vkey = main.auth.create_api_key(viewer, "x")
    assert up(env, key=vkey, path="Officina", data=GCODE + "; v\n").status_code == 403


def test_upload_and_print_creates_order(env, monkeypatch):
    main = env["main"]
    from app import production
    main.svc.printers["SN1"] = {"sn": "SN1", "name": "MK4 uno"}
    main.svc.printers["SN2"] = {"sn": "SN2", "name": "MK4 due"}
    monkeypatch.setattr(production, "check", lambda _svc, _f, sn: (sn == "SN1", "" if sn == "SN1" else "preparato per altro"))
    assert env["client"].get("/octoprint/g/nessuno/api/version", headers={"X-Api-Key": env["key"]}).status_code == 404
    gid = main.svc.db.x("INSERT INTO printer_groups(name) VALUES('Prusa')")
    for sn in ("SN1", "SN2"):
        main.svc.db.x("INSERT INTO group_printers(group_id, printer_sn) VALUES(?,?)", (gid, sn))
    r = up(env, print_=True, prefix="/octoprint/g/prusa")
    assert r.status_code == 201, r.text
    prod = r.json()["fabbrix"]["production_id"]
    row = main.svc.db.one("SELECT * FROM productions WHERE id=?", (prod,))
    assert row["status"] == "active" and row["printers"] == '["SN1"]' and row["name"] == "pezzo"
    assert main.svc.db.one("SELECT COUNT(*) n FROM production_units WHERE production_id=?", (prod,))["n"] == 1
    # solo stampanti incompatibili: file archiviato, ordine rifiutato
    r = up(env, print_=True, prefix="/octoprint/p/SN2", name="b.gcode", data=GCODE + "; b\n")
    assert r.status_code == 409
    # ordini in pausa se l'amministratore lo ha scelto
    main.svc.db.set_setting("ui_settings", {"slicer_orders_paused": True})
    r = up(env, print_=True, prefix=f"/octoprint/g/{gid}", name="c.gcode", data=GCODE + "; c\n")
    assert main.svc.db.one("SELECT status FROM productions WHERE id=?", (r.json()["fabbrix"]["production_id"],))["status"] == "paused"


