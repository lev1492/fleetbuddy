UA = {"User-Agent": "PrusaSlicer/2.8.1"}


@pytest.fixture()
def env(tmp_path, monkeypatch):
    cfg = tmp_path / "config.toml"
    cfg.write_text(f'[hub]\nhost = ""\n[app]\ndata_dir = "{(tmp_path / "data").as_posix()}"\n', encoding="utf-8")
    monkeypatch.setenv("FLEETBUDDY_CONFIG", str(cfg))
    for m in [m for m in sys.modules if m == "app" or m.startswith("app.")]:
        del sys.modules[m]
    main = importlib.import_module("app.main")
    from fastapi.testclient import TestClient

    from app import octoprint
    from app.auth import Auth, ensure_roles
    from app.service import Service
    # come lifespan(), ma senza il ciclo di lettura delle stampanti
    main.svc = Service(main.cfg)
    ensure_roles(main.svc.db)
    main.auth = Auth(main.svc.db)
    octoprint.init(svc=main.S, auth=lambda: main.auth, group_targetable=main.group_targetable, settings=main.settings,
                   can_prioritize=main.can_prioritize)
    admin = main.auth.create_user("admin", "Password123", "admin")
    _, key = main.auth.create_api_key(admin, "test")
    yield {"main": main, "client": TestClient(main.app), "key": key, "admin": admin}
    os.environ.pop("FLEETBUDDY_CONFIG", None)


def up(env, name="pezzo.gcode", path="", print_=False, prefix="/octoprint", key=None, data=GCODE):
    return env["client"].post(f"{prefix}/api/files/local", headers={"X-Api-Key": key or env["key"], **UA},
                              files={"file": (name, data.encode(), "application/octet-stream")},
                              data={"path": path, "print": "true" if print_ else "false"})


def test_version_requires_key(env):
    c = env["client"]
    assert c.get("/octoprint/api/version").status_code == 403
    assert c.get("/octoprint/api/version", headers={"X-Api-Key": "ffm_sbagliata"}).status_code == 403
    r = c.get("/octoprint/api/version", headers={"X-Api-Key": env["key"]})
    assert r.status_code == 200 and r.json()["text"].startswith("OctoPrint")
    # anche con chiave nella query e con Bearer
    assert c.get(f"/octoprint/api/version?apikey={env['key']}").status_code == 200
    assert c.get("/octoprint/api/version", headers={"Authorization": f"Bearer {env['key']}"}).status_code == 200


