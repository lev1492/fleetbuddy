"""G-code Bambu Lab (esportato come .gcode da Bambu Studio / OrcaSlicer) → .gcode.3mf stampabile dal Fleet Hub.

Il Fleet Hub stampa solo file .gcode.3mf (documentazione Fleet Hub, paragrafo 5): un archivio ZIP con
Metadata/plate_1.gcode e Metadata/slice_info.config, da cui ricava i filamenti da abbinare agli slot AMS.
Dal G-code si ricavano modello, ugelli, durata, peso e filamenti usati (cambi filamento M620); il G-code
resta identico, con il suo controllo MD5.
"""
from __future__ import annotations

import hashlib
import json
import re
import zipfile
from pathlib import Path
from xml.sax.saxutils import quoteattr

# Codici modello usati da Bambu Studio in slice_info.config (printer_model_id). Solo quelli certi: per gli altri
# il campo si omette (Farm Manager controlla la compatibilità con il nome del modello).
MODEL_IDS = {"Bambu Lab X1 Carbon": "BL-P001", "Bambu Lab X1": "BL-P002", "Bambu Lab P1P": "C11", "Bambu Lab P1S": "C12",
             "Bambu Lab X1E": "C13", "Bambu Lab A1 mini": "N1", "Bambu Lab A1": "N2S", "Bambu Lab H2D": "O1D"}


def _header(path: Path, limit: int = 2 << 20) -> str:
    with open(path, "rb") as fh:
        return fh.read(limit).decode("utf-8", "replace")


def is_bambu_gcode(path: str | Path) -> bool:
    """G-code di Bambu Studio / OrcaSlicer preparato per una stampante Bambu Lab."""
    head = _header(Path(path), 256 << 10)
    slicer = re.search(r"^; (BambuStudio|OrcaSlicer|generated by OrcaSlicer)", head, re.M)
    model = re.search(r"^; printer_model = (Bambu Lab .+)$", head, re.M)
    return bool(slicer and model)


def _config(text: str) -> dict:
    """Coppie "; chiave = valore" del blocco di configurazione."""
    m = re.search(r"; CONFIG_BLOCK_START(.*?); CONFIG_BLOCK_END", text, re.S)
    block = m.group(1) if m else text
    return {k.strip(): v.strip() for k, v in re.findall(r"^; ([a-zA-Z0-9_ \[\]]+?) = (.*)$", block, re.M)}


def _split(v: str) -> list[str]:
    v = (v or "").strip()
    if not v:
        return []
    sep = ";" if ";" in v else ","
    return [x.strip().strip('"') for x in v.split(sep)]


def _secs(s: str) -> int:
    total = 0
    for n, u in re.findall(r"(\d+)\s*([dhms])", s or ""):
        total += int(n) * {"d": 86400, "h": 3600, "m": 60, "s": 1}[u]
    return total


def convert(src: str | Path, dst: str | Path) -> dict:
    """Crea il .gcode.3mf e restituisce un riepilogo (modello, filamenti usati, durata, peso)."""
    src, dst = Path(src), Path(dst)
    data = src.read_bytes()
    text = data.decode("utf-8", "replace")
    head = text[: 1 << 20]
    cfg = _config(head)
    model = cfg.get("printer_model", "")
    nozzles = [x for x in _split(cfg.get("nozzle_diameter", "")) if x]
    types, colors, ids = _split(cfg.get("filament_type", "")), _split(cfg.get("filament_colour", "")), _split(cfg.get("filament_ids", ""))
    fmap = [int(x) for x in _split(cfg.get("filament_map", "")) if x.isdigit()]       # ugello (1, 2) di ogni filamento
    vol_types = _split(cfg.get("nozzle_volume_type", ""))
    density = [float(x) for x in _split(cfg.get("filament_density", "")) if re.match(r"^[\d.]+$", x)]
    # filamenti usati: cambi filamento "M620 S<n>A" (n da 0); senza cambi, il primo
    used = sorted({int(n) for n in re.findall(r"^M620 S(\d+)A", text, re.M) if int(n) < 255}) or [0]
    m_t = re.search(r"total estimated time:\s*([^\n;]+)", head)
    secs = _secs(m_t.group(1)) if m_t else 0
    m_w = re.search(r"total filament weight \[g\]\s*:\s*([\d.]+)", head)
    m_l = re.search(r"total filament length \[mm\]\s*:\s*([\d.]+)", head)
    weight, length_m = float(m_w.group(1)) if m_w else 0.0, (float(m_l.group(1)) / 1000 if m_l else 0.0)
    m_layers = re.search(r"total layer number:\s*(\d+)", head)
    # il G-code dà solo il totale: diviso tra i filamenti usati (uno solo nella maggior parte dei casi)
    share = 1 / len(used)
    fil_xml, fils = [], []
    for i in used:
        noz = fmap[i] if i < len(fmap) else 1
        f = {"id": i + 1, "type": types[i] if i < len(types) else "", "color": (colors[i] if i < len(colors) else "#888888").upper(),
             "tray_info_idx": ids[i] if i < len(ids) else "", "used_g": round(weight * share, 2), "used_m": round(length_m * share, 2),
             "nozzle": noz}
        fils.append(f)
        attrs = {"id": f["id"], "tray_info_idx": f["tray_info_idx"], "type": f["type"], "color": f["color"],
                 "used_m": f"{f['used_m']:.2f}", "used_g": f"{f['used_g']:.2f}", "group_id": noz - 1}
        if nozzles:
            attrs["nozzle_diameter"] = nozzles[min(noz - 1, len(nozzles) - 1)]
        if vol_types:
            attrs["volume_type"] = vol_types[min(noz - 1, len(vol_types) - 1)]
        fil_xml.append("    <filament " + " ".join(f"{k}={quoteattr(str(v))}" for k, v in attrs.items()) + "/>")
    meta = {"index": "1", "extruder_type": "0", "nozzle_diameters": nozzles[0] if nozzles else "",
            "timelapse_type": "0", "prediction": str(secs), "weight": f"{weight:.2f}", "outside": "false",
            "support_used": "false", "label_object_enabled": "false",
            "filament_maps": " ".join(str(x) for x in fmap) if fmap else ""}
    if model in MODEL_IDS:
        meta["printer_model_id"] = MODEL_IDS[model]
    slicer = re.search(r"^; (BambuStudio|OrcaSlicer) ([\d.]+)", head, re.M)
    slice_info = ('<?xml version="1.0" encoding="UTF-8"?>\n<config>\n  <header>\n'
                  '    <header_item key="X-BBL-Client-Type" value="slicer"/>\n'
                  f'    <header_item key="X-BBL-Client-Version" value={quoteattr(slicer.group(2) if slicer else "")}/>\n'
                  '  </header>\n  <plate>\n'
                  + "".join(f"    <metadata key={quoteattr(k)} value={quoteattr(v)}/>\n" for k, v in meta.items() if v != "")
                  + "\n".join(fil_xml) + "\n  </plate>\n</config>\n")
    project = {"printer_model": model, "printer_settings_id": cfg.get("printer_settings_id", "").strip('"'),
               "nozzle_diameter": nozzles, "filament_type": types, "filament_colour": colors, "filament_ids": ids,
               "filament_density": [str(x) for x in density], "filament_map": [str(x) for x in fmap],
               "curr_bed_type": cfg.get("curr_bed_type", ""), "from": "Fabbrix Farm Manager (G-code Bambu impacchettato)"}
    content_types = ('<?xml version="1.0" encoding="UTF-8"?>\n<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">\n'
                     ' <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>\n'
                     ' <Default Extension="model" ContentType="application/vnd.ms-package.3dmanufacturing-3dmodel+xml"/>\n'
                     ' <Default Extension="png" ContentType="image/png"/>\n'
                     ' <Default Extension="gcode" ContentType="text/x.gcode"/>\n</Types>\n')
    rels = ('<?xml version="1.0" encoding="UTF-8"?>\n<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">\n'
            ' <Relationship Target="/3D/3dmodel.model" Id="rel-1" Type="http://schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel"/>\n'
            '</Relationships>\n')
    model_xml = ('<?xml version="1.0" encoding="UTF-8"?>\n<model unit="millimeter" xml:lang="en-US" '
                 'xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02">\n'
                 f' <metadata name="Application">{"BambuStudio-" + slicer.group(2) if slicer else "BambuStudio"}</metadata>\n'
                 ' <resources/>\n <build/>\n</model>\n')
    # date fisse: lo stesso G-code produce sempre lo stesso archivio (Farm Manager riconosce i doppioni dal contenuto)
    parts = [("[Content_Types].xml", content_types), ("_rels/.rels", rels), ("3D/3dmodel.model", model_xml),
             ("Metadata/plate_1.gcode", data), ("Metadata/plate_1.gcode.md5", hashlib.md5(data).hexdigest().upper()),
             ("Metadata/slice_info.config", slice_info), ("Metadata/project_settings.config", json.dumps(project, indent=1))]
    with zipfile.ZipFile(dst, "w", zipfile.ZIP_DEFLATED) as z:
        for name, content in parts:
            zi = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            zi.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(zi, content)
    return {"model": model, "filaments": fils, "seconds": secs, "weight_g": weight,
            "layers": int(m_layers.group(1)) if m_layers else 0}
